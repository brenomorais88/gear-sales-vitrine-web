function buildAnuncio(
  partial: Omit<VitrineAnuncio, "imagemCapaUrl" | "imagens"> & { imageSeed: string }
): VitrineAnuncio {
  const { imageSeed, ...rest } = partial
  const capa = getMockVehicleImageUrl(imageSeed)
  const extras = [1, 2, 3].map((n) =>
    getMockVehicleImageUrl(`${imageSeed}-${n}`, 800, 600)
  )

  return {
    ...rest,
    imagemCapaUrl: capa,
    imagens: [capa, ...extras],
  }
}

