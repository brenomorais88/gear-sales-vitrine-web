export function getAnunciosMockByLojaId(lojaId: string): VitrineAnuncio[] {
  if (lojaId !== VITRINE_LOJA_MOCK_ID) {
    return []
  }
  return anunciosMock
}

export function getAnuncioMockById(
  lojaId: string,
  anuncioId: string
): VitrineAnuncio | undefined {
  return getAnunciosMockByLojaId(lojaId).find((a) => a.id === anuncioId)
}
